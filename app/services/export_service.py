import io
from typing import Dict, Any
from datetime import datetime
from app.db import get_fiat_collection_name


async def _get_extended_stats(db: Any) -> Dict[str, Any]:
    today_midnight = datetime.now().replace(hour=0, minute=0, second=0, microsecond=0)
    total_users = await db["Users"].count_documents({})
    dau = await db["Users"].count_documents({"last_active": {"$gte": today_midnight}})
    total_groups = await db["Groups"].count_documents({"Status": "Active"})
    total_fiat = await db[get_fiat_collection_name()].count_documents({})

    agg = await db["Users"].aggregate(
        [{"$group": {"_id": None, "total": {"$sum": {"$ifNull": ["$stats.total_requests", 0]}}}}]
    ).to_list(length=1)
    total_reqs = agg[0]["total"] if agg else 0

    from app.config import LOGS_DIR
    from app.utils.logs import count_log_lines

    errors_today = await count_log_lines(LOGS_DIR / "errors.log", datetime.now().strftime("%Y-%m-%d"))

    db_stats = await db.command("dbstats")
    size_mb = db_stats.get("dataSize", 0) / (1024 * 1024)

    return {
        "Total Users": total_users,
        "DAU": dau,
        "Total Groups": total_groups,
        "Total Fiat Rates": total_fiat,
        "Total Requests": total_reqs,
        "Errors Today": errors_today,
        "DB Size (MB)": round(size_mb, 2),
    }


async def export_stats_csv(db: Any) -> io.BytesIO:
    """Generate a CSV export of current statistics."""
    import csv

    stats = await _get_extended_stats(db)

    output = io.StringIO()
    writer = csv.writer(output)
    writer.writerow(["Metric", "Value"])
    for k, v in stats.items():
        writer.writerow([k, v])

    return io.BytesIO(output.getvalue().encode("utf-8"))


async def export_stats_markdown(db: Any) -> io.BytesIO:
    """Generate a Markdown export of current statistics."""
    stats = await _get_extended_stats(db)

    md_content = "# System Statistics Report\n\n## Overview\n"
    for k, v in stats.items():
        md_content += f"- **{k}:** `{v}`\n"

    md_content += "\n*Generated by finances bot.*\n"
    return io.BytesIO(md_content.encode("utf-8"))
